export const i18nState = reactive({
  locale: localStorage.getItem('wx_locale') || 'zh-CN'
})

export const t = (path) => {
  const keys = path.split('.')
  let current = messages[i18nState.locale] || messages['zh-CN']
  for (const k of keys) {
    if (current && current[k] !== undefined) {
      current = current[k]
    } else {
      let fallback = messages['zh-CN']
      for (const fk of keys) {
        if (fallback && fallback[fk] !== undefined) {
          fallback = fallback[fk]
        } else {
          return path
        }
      }
      return fallback
    }
  }
  return current
}

export const setLocale = (locale) => {
  if (messages[locale]) {
    i18nState.locale = locale
    localStorage.setItem('wx_locale', locale)
  }
}

export const toggleLocale = () => {
  const next = i18nState.locale === 'zh-CN' ? 'en-US' : 'zh-CN'
  setLocale(next)
}
